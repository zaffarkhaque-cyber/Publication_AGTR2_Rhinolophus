#!/usr/bin/env python3
"""
TABLE1_to_excel.py - collects the output of TABLE1.py into one Excel workbook.

Usage:  python TABLE1_to_excel.py <results folder> <output .xlsx>
Reads:  TABLE1.tsv, TABLE1_controls.txt, TABLE1_disruptions.tsv, TABLE1_shared_disruptions.txt,
        TABLE1_alignment.fasta, TABLE1_gene_models.tsv, TABLE1_run_log.txt
Needs:  Python 3 with pandas and openpyxl.
"""
import os
import re
import sys

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

FONT = "Arial"
HEAD = PatternFill("solid", fgColor="1F3864")
STATUS_FILL = {"NOT_FOUND": "F8CBAD", "FOUND_DISRUPTED": "FFE699", "FOUND": "C6EFCE", "PARTIAL": "FFE699",
               "SKIPPED": "D9D9D9", "PASS": "C6EFCE", "FAIL": "FF7C80", "STOP": "F8CBAD", "FRAME_CHANGE": "BDD7EE"}
THIN = Side(style="thin", color="BFBFBF")
FOCUS = ["Aselliscus_stoliczkanus", "Hipposideros_armiger", "Hipposideros_larvatus"]
REFS = ["Homo_sapiens", "Myotis_myotis", "Megaderma_spasma", "Rousettus_aegyptiacus"]


def fasta(path):
    d, cur = {}, None
    for ln in open(path):
        ln = ln.strip()
        if ln.startswith(">"):
            cur = ln[1:].split()[0]
            d[cur] = ""
        elif cur:
            d[cur] += ln
    return d


def write_table(ws, df, start_row=1, widths=None, status_cols=()):
    for j, c in enumerate(df.columns, 1):
        cell = ws.cell(start_row, j, c)
        cell.font = Font(name=FONT, bold=True, color="FFFFFF")
        cell.fill = HEAD
        cell.alignment = Alignment(wrap_text=True, vertical="center")
    for i, row in enumerate(df.itertuples(index=False), start_row + 1):
        for j, v in enumerate(row, 1):
            if isinstance(v, float) and v.is_integer():
                v = int(v)
            cell = ws.cell(i, j, None if (isinstance(v, float) and pd.isna(v)) else v)
            cell.font = Font(name=FONT)
            cell.border = Border(top=THIN, bottom=THIN, left=THIN, right=THIN)
            cell.alignment = Alignment(vertical="top", wrap_text=False)
            if df.columns[j - 1] in status_cols and str(v) in STATUS_FILL:
                cell.fill = PatternFill("solid", fgColor=STATUS_FILL[str(v)])
                cell.font = Font(name=FONT, bold=True)
    ws.row_dimensions[start_row].height = 45
    ws.freeze_panes = ws.cell(start_row + 1, 2)
    for j, c in enumerate(df.columns, 1):
        w = (widths or {}).get(c)
        if w is None:
            w = min(45, max(10, len(str(c)) * 0.6, *(len(str(x)) * 1.05 for x in df[c].head(60))))
        ws.column_dimensions[get_column_letter(j)].width = w
    return start_row + len(df) + 1


def note(ws, row, text, bold=False, size=10, color="000000"):
    c = ws.cell(row, 1, text)
    c.font = Font(name=FONT, bold=bold, size=size, color=color)
    return row + 1


def main(res, out):
    t1 = pd.read_csv(os.path.join(res, "TABLE1.tsv"), sep="\t", dtype=str)
    models = pd.read_csv(os.path.join(res, "TABLE1_gene_models.tsv"), sep="\t", dtype=str)
    dis = pd.read_csv(os.path.join(res, "TABLE1_disruptions.tsv"), sep="\t", dtype=str)
    fa = fasta(os.path.join(res, "TABLE1_alignment.fasta"))
    human_key = next(k for k in fa if k.startswith("Homo_sapiens_") and k.endswith("_query"))
    controls = open(os.path.join(res, "TABLE1_controls.txt")).read().splitlines()
    shared_txt = open(os.path.join(res, "TABLE1_shared_disruptions.txt")).read().splitlines()
    log = open(os.path.join(res, "TABLE1_run_log.txt")).read().splitlines()

    wb = Workbook()

    # ------------------------------------------------------------------ 1 Overview
    ws = wb.active
    ws.title = "1 Overview"
    r = note(ws, 1, "AGTR2 locus evaluation - results workbook", bold=True, size=14)
    r = note(ws, r, "Generated by TABLE1_to_excel.py from the folder: %s" % os.path.abspath(res), size=9,
             color="595959")
    r += 1
    r = note(ws, r, "Sheets", bold=True)
    for s, d in [("2 Table 1", "One row per genome: AGTR2 call, locations of AGTR2 / PLS3 / SLC6A14, the PLS3-SLC6A14 "
                               "interval and its N content."),
                 ("3 Controls", "Expected-present genomes must give FOUND; expected-absent (published loss) NOT_FOUND."),
                 ("4 AGTR2 disruptions", "Every stop codon and reading-frame change in each AGTR2 copy, on human "
                                         "AGTR2 (NP_000677.2) positions, with the codon read from the genome."),
                 ("5 Shared vs private", "Each disruption position: which hipposiderid has it, and the residue "
                                         "every relevant species has at that position."),
                 ("6 PLS3 copies", "Every PLS3-query gene model: the real X-linked PLS3, retrocopies, and paralogs "
                                   "(PLS1, LCP1)."),
                 ("7 All gene models", "Every tblastn gene model for every query and genome (raw)."),
                 ("8 Run log", "Software versions, parameters, input checksums.")]:
        ws.cell(r, 1, s).font = Font(name=FONT, bold=True)
        ws.cell(r, 2, d).font = Font(name=FONT)
        r += 1
    r += 1
    r = note(ws, r, "Counts (formulas on sheet '2 Table 1')", bold=True)
    calls = ["FOUND", "FOUND_DISRUPTED", "NOT_FOUND", "PARTIAL", "SKIPPED"]
    n = len(t1) + 1
    CALLCOL = get_column_letter(list(t1.columns).index("AGTR2 call") + 1)   # not hardcoded: the column may move
    for cname in calls:
        ws.cell(r, 1, "AGTR2 %s" % cname).font = Font(name=FONT)
        c = ws.cell(r, 2, "=COUNTIF('2 Table 1'!${0}$2:${0}${1},\"{2}\")".format(CALLCOL, n, cname))
        c.font = Font(name=FONT, bold=True)
        if cname in STATUS_FILL:
            ws.cell(r, 1).fill = PatternFill("solid", fgColor=STATUS_FILL[cname])
        r += 1
    ws.cell(r, 1, "Genomes in table").font = Font(name=FONT)
    ws.cell(r, 2, "=COUNTA('2 Table 1'!$A$2:$A$%d)" % n).font = Font(name=FONT, bold=True)
    r += 1
    ws.cell(r, 1, "Controls PASS").font = Font(name=FONT)
    ws.cell(r, 2, "=COUNTIF('3 Controls'!$E:$E,\"PASS\")").font = Font(name=FONT, bold=True)
    r += 1
    ws.cell(r, 1, "Controls FAIL").font = Font(name=FONT)
    ws.cell(r, 2, "=COUNTIF('3 Controls'!$E:$E,\"FAIL\")").font = Font(name=FONT, bold=True)
    r += 2
    r = note(ws, r, "Colour key", bold=True)
    for k, d in [("FOUND", "intact AGTR2 (one continuous reading frame, no stop codon)"),
                 ("FOUND_DISRUPTED", "AGTR2 present but with stop codon(s) / frame changes"),
                 ("NOT_FOUND", "no AGTR2 ortholog in the genome"),
                 ("STOP", "stop codon"), ("FRAME_CHANGE", "reading-frame change (frameshift)")]:
        ws.cell(r, 1, k).fill = PatternFill("solid", fgColor=STATUS_FILL[k])
        ws.cell(r, 1).font = Font(name=FONT, bold=True)
        ws.cell(r, 2, d).font = Font(name=FONT)
        r += 1
    ws.column_dimensions["A"].width = 26
    ws.column_dimensions["B"].width = 110

    # ------------------------------------------------------------------ 2 Table 1
    ws = wb.create_sheet("2 Table 1")
    write_table(ws, t1, status_cols=("AGTR2 call",))

    # ------------------------------------------------------------------ 3 Controls
    ws = wb.create_sheet("3 Controls")
    rows = []
    for ln in controls[1:]:
        m = re.match(r"\s*(\S+)\s+expected\s+(\S+)\s+got\s+(\S+)\s+(PASS|FAIL)", ln)
        if m:
            rows.append(dict(species=m.group(1), expected=m.group(2),
                             group=t1.set_index("species").loc[m.group(1), "group"] if m.group(1) in set(t1.species)
                             else "", got=m.group(3), result=m.group(4)))
    df = pd.DataFrame(rows, columns=["species", "group", "expected", "got", "result"])
    end = write_table(ws, df, status_cols=("got", "result"))
    neg = [l.strip() for l in shared_txt if "NEGATIVE CONTROL" in l]
    if neg:
        end += 1
        c = ws.cell(end, 1, neg[0])
        c.font = Font(name=FONT, bold=True)
        c.fill = PatternFill("solid", fgColor=STATUS_FILL["PASS" if neg[0].endswith("PASS") else "FAIL"])

    # ------------------------------------------------------------------ 4 Disruptions
    ws = wb.create_sheet("4 AGTR2 disruptions")
    d = dis[dis["event"] != "none"].copy()
    d["sort"] = d.iloc[:, 3].str.extract(r"(\d+)").astype(float)
    d = d.sort_values(["species", "sort"]).drop(columns="sort")
    end = write_table(ws, d, status_cols=("event",))
    end += 1
    ws.cell(end, 1, "Species with no disruption (continuous reading frame, no stop codon):").font = \
        Font(name=FONT, bold=True)
    for s in dis[dis["event"] == "none"]["species"]:
        end += 1
        ws.cell(end, 1, s).font = Font(name=FONT)

    # ------------------------------------------------------------------ 5 Shared vs private
    ws = wb.create_sheet("5 Shared vs private")
    ev = {}
    for _, e in d[d.species.isin(FOCUS)].iterrows():
        pos = e.iloc[3]
        key = (e["event"], pos)
        ev.setdefault(key, {})[e["species"]] = e["codon"] if e["event"] == "STOP" else "frameshift"
    refs = [s for s in REFS if s in fa]
    cols = ["event", "human AGTR2 position"] + ["%s" % s for s in FOCUS] + ["n hipposiderids with it"] + \
           ["residue: Human"] + ["residue: %s" % s for s in refs if s != "Homo_sapiens"] + \
           ["residue: %s" % s for s in FOCUS]
    for j, c in enumerate(cols, 1):
        cell = ws.cell(1, j, c)
        cell.font = Font(name=FONT, bold=True, color="FFFFFF")
        cell.fill = HEAD
        cell.alignment = Alignment(wrap_text=True, vertical="center")
    ws.row_dimensions[1].height = 45
    first = lambda p: int(re.match(r"\d+", p).group(0))
    for i, (key, sp) in enumerate(sorted(ev.items(), key=lambda kv: (first(kv[0][1]), kv[0][0])), 2):
        typ, pos = key
        p = first(pos)
        vals = [typ, pos] + [sp.get(s, "") for s in FOCUS]
        for j, v in enumerate(vals, 1):
            c = ws.cell(i, j, v)
            c.font = Font(name=FONT, bold=j > 2 and bool(v))
            c.border = Border(top=THIN, bottom=THIN, left=THIN, right=THIN)
            if j > 2 and v:
                c.fill = PatternFill("solid", fgColor=STATUS_FILL[typ])
        if typ in STATUS_FILL:
            ws.cell(i, 1).fill = PatternFill("solid", fgColor=STATUS_FILL[typ])
        jn = 3 + len(FOCUS)
        c = ws.cell(i, jn, '=COUNTIF(%s%d:%s%d,"?*")' % (get_column_letter(3), i, get_column_letter(jn - 1), i))
        c.font = Font(name=FONT, bold=True)
        c.border = Border(top=THIN, bottom=THIN, left=THIN, right=THIN)
        res_sp = [human_key] + [s for s in refs if s != "Homo_sapiens"] + FOCUS
        for k, s in enumerate(res_sp):
            seq = fa.get(s, "")
            c = ws.cell(i, jn + 1 + k, seq[p - 1] if p <= len(seq) else "")
            c.font = Font(name="Courier New", bold=c.value == "*")
            c.alignment = Alignment(horizontal="center")
            c.border = Border(top=THIN, bottom=THIN, left=THIN, right=THIN)
            if c.value == "*":
                c.fill = PatternFill("solid", fgColor=STATUS_FILL["STOP"])
    last = len(ev) + 1
    for j in range(1, len(cols) + 1):
        ws.column_dimensions[get_column_letter(j)].width = 14 if j > 2 else 16
    ws.freeze_panes = "C2"
    r = last + 2
    for t in ["How to read this sheet:",
              "Columns C-E: the codon (for stops) or 'frameshift' in each hipposiderid; blank = that species does "
              "NOT have this disruption.",
              "Column F: number of the three hipposiderids carrying it (formula).",
              "Columns G onward: amino acid each species has at that human position in the alignment "
              "('*' = stop, '-' = no aligned sequence). A blank in C-E together with a normal residue here means "
              "the species has sequence at that position and no stop there.",
              "Stops count as the same event only at exactly the same position; frame changes within 3 aa."]:
        ws.cell(r, 1, t).font = Font(name=FONT, bold=t.endswith(":"))
        r += 1

    # ------------------------------------------------------------------ 6 PLS3 copies
    ws = wb.create_sheet("6 PLS3 copies")
    p3 = models[models["query"] == "PLS3"].copy()
    cls = []
    for _, m in p3.iterrows():
        if m["orthologous to query"] != "yes":
            cls.append("other gene: %s" % m["best match in human proteome"])
        elif int(m["exon hits"]) >= 8 and int(m["internal stop codons"]) == 0:
            cls.append("PLS3 (multi-exon, intact)")
        else:
            cls.append("PLS3-like copy: %s exon hit(s), %s stop codon(s)" % (m["exon hits"], m["internal stop codons"]))
    p3.insert(2, "classification", cls)
    p3["_o"] = p3["classification"].map(lambda c: 0 if c.startswith("PLS3 (") else 1 if c.startswith("PLS3-like")
                                        else 2)
    p3 = p3.sort_values(["species", "_o", "model rank"]).drop(columns="_o")
    write_table(ws, p3)

    # ------------------------------------------------------------------ 7 All gene models, 8 Run log
    write_table(wb.create_sheet("7 All gene models"), models)
    ws = wb.create_sheet("8 Run log")
    for i, ln in enumerate(log, 1):
        ws.cell(i, 1, ln).font = Font(name="Courier New", size=9)
    ws.column_dimensions["A"].width = 160

    wb.save(out)
    print("Saved %s" % out)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
