#!/usr/bin/env python3
"""
MATERIALS_AND_METHODS.py - assembles one Materials and Methods file from the text each analysis generated
about its own run, so that nothing in it is typed by hand and nothing can drift from what was executed.

Usage:  python MATERIALS_AND_METHODS.py [TABLE1 results] [FIGURE3 results] [output file]
Default: ./results  ../FIGURE3_Intergenic_AGTR2_PSEUDOGENE_SCreen/results  MATERIALS_AND_METHODS.txt

Every figure in the output is read from the run that produced it. Software versions and the checksums of the
scripts and input files are in each analysis's own run log, named at the end.
"""
import datetime
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PARTS = [("1. Identification of AGTR2 and its flanking genes across genomes (Table 1)",
          "TABLE1_methods.txt", "TABLE1_run_log.txt"),
         ("2. Scan of the PLS3-SLC6A14 intergenic region for residual AGTR2 sequence",
          "INTERGENIC_methods.txt", "INTERGENIC_run_log.txt")]


def main(a, b, out):
    chunks = ["MATERIALS AND METHODS",
              "Assembled %s by MATERIALS_AND_METHODS.py from the text each analysis wrote about its own run."
              % datetime.date.today().isoformat(),
              ""]
    missing = []
    for folder, (title, meth, log) in zip((a, b), PARTS):
        p = os.path.join(folder, meth)
        chunks.append("=" * 100)
        chunks.append(title)
        chunks.append("=" * 100)
        if not os.path.exists(p):
            missing.append(p)
            chunks.append("  [not available: %s has not been run, or its results are in another folder]\n" % meth)
            continue
        body = open(p, encoding="utf-8").read().splitlines()
        # drop the generated file's own header lines; the combined file has its own
        while body and (not body[0].strip() or body[0].startswith(("METHODS", "Generated by"))):
            body.pop(0)
        chunks.append("\n".join(body).rstrip())
        chunks.append("\nSoftware versions, parameters and the checksums of the script and every input file for "
                      "this analysis are recorded in %s/%s." % (os.path.basename(folder), log))
        chunks.append("")
    chunks.append("=" * 100)
    chunks.append("Data and code availability")
    chunks.append("=" * 100)
    chunks.append("All analysis code, the genome list with NCBI assembly accessions, and the output of the runs "
                  "described above are available at <REPOSITORY URL>. The analyses use only publicly available "
                  "genome assemblies; each assembly's accession is given in TABLE1.tsv.")
    open(out, "w", encoding="utf-8").write("\n".join(chunks) + "\n")
    print("Wrote %s (%d bytes)" % (out, os.path.getsize(out)))
    if missing:
        print("NOTE: these were not found, so their sections are placeholders:")
        for p in missing:
            print("  " + p)


if __name__ == "__main__":
    args = sys.argv[1:]
    fig3 = os.path.join(os.path.dirname(HERE), "FIGURE3_Intergenic_AGTR2_PSEUDOGENE_SCreen", "results")
    if not os.path.isdir(fig3):                       # fall back to a results folder beside this script
        fig3 = os.path.join(HERE, "results_intergenic")
    main(args[0] if len(args) > 0 else os.path.join(HERE, "results"),
         args[1] if len(args) > 1 else fig3,
         args[2] if len(args) > 2 else os.path.join(HERE, "MATERIALS_AND_METHODS.txt"))
