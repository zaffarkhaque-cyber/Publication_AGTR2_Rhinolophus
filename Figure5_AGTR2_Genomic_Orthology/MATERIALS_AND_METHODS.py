#!/usr/bin/env python3
"""
MATERIALS_AND_METHODS.py - assembles a Materials and Methods file from the text each analysis generated
about its own run, so that nothing in it is typed by hand and nothing can drift from what was executed.

Run it with no arguments from this folder:

    python MATERIALS_AND_METHODS.py

It always includes this analysis (the whole-genome AGTR2 orthology screen). If the companion analyses are
present beside this folder it includes those too, in paper order, so the same command produces either the
section for this figure alone or the full Methods for the paper. Sections it cannot find are listed at the
end of the run rather than silently omitted.

    python MATERIALS_AND_METHODS.py --out ../MATERIALS_AND_METHODS.txt
    python MATERIALS_AND_METHODS.py --only-this-analysis
"""
import argparse
import datetime
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HOME = os.path.expanduser("~")

# Where the companion analyses might live. This folder can be moved anywhere - onto the Desktop, into a
# repository - without the other two having to move with it, so they are searched for rather than assumed
# to sit beside it. $AGTR2_ROOT, or --companions, overrides the search.
ROOTS = [os.environ.get("AGTR2_ROOT"), os.path.dirname(HERE), HERE,
         os.path.join(HOME, "OneDrive", "AGTR2"), os.path.join(HOME, "AGTR2"),
         os.path.join(HOME, "OneDrive", "Desktop"), os.path.join(HOME, "Desktop")]


def find(folder, marker, roots):
    """First <root>/<folder>/results that actually contains the generated methods file."""
    for r in roots:
        if r:
            p = os.path.join(r, folder, "results")
            if os.path.exists(os.path.join(p, marker)):
                return p
    return os.path.join(os.path.dirname(HERE), folder, "results")      # for the message when missing


def parts(roots):
    """(section title, folder holding the results, generated methods file, run log)"""
    return [
        ("Identification of AGTR2 and its flanking genes across genomes (Table 1)",
         find("TABLE1", "TABLE1_methods.txt", roots), "TABLE1_methods.txt", "TABLE1_run_log.txt"),
        ("Scan of the PLS3-SLC6A14 intergenic region for residual AGTR2 sequence",
         find("FIGURE3_Intergenic_AGTR2_PSEUDOGENE_SCreen", "INTERGENIC_methods.txt", roots),
         "INTERGENIC_methods.txt", "INTERGENIC_run_log.txt"),
        ("Whole-genome AGTR2 orthology screen (Figure 5)",
         os.path.join(HERE, "results"), "FIGURE5_methods.txt", "FIGURE5_run_log.txt"),
    ]


def main():
    ap = argparse.ArgumentParser(description="Assemble Materials and Methods from the generated run texts")
    ap.add_argument("--out", default=os.path.join(HERE, "MATERIALS_AND_METHODS.txt"))
    ap.add_argument("--only-this-analysis", action="store_true",
                    help="write the section for the orthology screen alone")
    ap.add_argument("--companions", default=None,
                    help="folder holding TABLE1/ and FIGURE3_.../ , if they are not found automatically")
    a = ap.parse_args()
    roots = ([os.path.abspath(a.companions)] if a.companions else []) + ROOTS
    allparts = parts(roots)
    chosen = [allparts[-1]] if a.only_this_analysis else allparts

    chunks = ["MATERIALS AND METHODS",
              "Assembled %s by MATERIALS_AND_METHODS.py from the text each analysis wrote about its own run. "
              "Nothing here is typed by hand." % datetime.date.today().isoformat(), ""]
    missing, n = [], 0
    for title, folder, meth, log in chosen:
        p = os.path.join(folder, meth)
        n += 1
        chunks += ["=" * 100, "%d. %s" % (n, title), "=" * 100]
        if not os.path.exists(p):
            missing.append(p)
            chunks.append("  [not available: this analysis has not been run, or its results are elsewhere]\n")
            continue
        body = open(p, encoding="utf-8").read().splitlines()
        while body and (not body[0].strip() or body[0].startswith(("METHODS", "Generated by"))):
            body.pop(0)            # drop the generated file's own header; this document has its own
        chunks.append("\n".join(body).rstrip())
        chunks.append("\nSoftware versions, parameters and the checksums of the script and every input file "
                      "for this analysis are recorded in %s/%s." % (os.path.basename(os.path.dirname(folder)), log))
        # name the exact folder this text came from: copies of an analysis can exist in more than one place
        chunks.append("Read from: %s (written %s)" % (
            folder, datetime.datetime.fromtimestamp(os.path.getmtime(p)).isoformat(timespec="seconds")))
        chunks.append("")
        print("  %d. %s\n       <- %s" % (n, title, folder))
    chunks += ["=" * 100, "Data and code availability", "=" * 100,
               "All analysis code, the genome list with NCBI assembly accessions, and the output of the runs "
               "described above are available at <REPOSITORY URL>. The analyses use only publicly available "
               "genome assemblies; every assembly accession is given in genomes.tsv and repeated in each "
               "analysis's results table."]
    open(a.out, "w", encoding="utf-8").write("\n".join(chunks) + "\n")
    print("Wrote %s (%d bytes, %d section(s))" % (a.out, os.path.getsize(a.out), n))
    if missing:
        print("\nNOTE: these were not found, so their sections are placeholders. Run those analyses, or pass")
        print("--only-this-analysis if you want the orthology screen on its own:")
        for p in missing:
            print("  " + p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
