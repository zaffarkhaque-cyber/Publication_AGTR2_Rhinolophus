#!/usr/bin/env python3
"""
make_github_package.py - build the folder to upload to GitHub for this analysis.

It copies the code, the genome list and the output of the published run into a clean directory, and
removes anything local to one machine:

  * absolute paths under your home directory become <PATH>, in every text file, including the run log -
    checksums, software versions and assembly provenance are kept, your directory layout is not;
  * the REFERENCE and DB_DIR lines of the run script become documented placeholders;
  * genomes.tsv keeps every NCBI accession but its last column becomes genomes/<accession>.zip, the
    convention the README describes, so nobody inherits your paths;
  * a .gitignore is written for the things that are large or regenerated.

Nothing is hard-coded to one analysis: the code files are whatever sits beside this script, and the
results are whatever the run wrote, minus the regenerable bulk. Everything skipped is PRINTED with the
reason, so no file is ever dropped silently.

    python make_github_package.py
    python make_github_package.py --out /path/to/GITHUB_UPLOAD/<this analysis>

Run it from inside the analysis folder, after the analysis itself and after MATERIALS_AND_METHODS.py.
"""
import argparse
import csv
import os
import re
import shutil
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = os.path.basename(HERE)
BINARY = (".png", ".pdf", ".gz", ".zip")
# An .xlsx is a ZIP of XML, so it is TEXT wearing a binary coat: it carries the paths the run was made
# with, in the sheets and in the run-log sheet. Copying it verbatim and then skipping it in the leak
# check is how a home directory gets published inside a file nobody thinks to open.
ZIPPED_XML = (".xlsx", ".docx", ".pptx")
XML_MEMBER = (".xml", ".rels", ".txt")

# Code and documentation: picked up by extension, so adding a script to the analysis adds it to the
# package. genomes.tsv is handled separately (its paths are rewritten), never copied as-is.
CODE_EXT = (".py", ".sh", ".md", ".faa", ".xlsx", ".txt")
CODE_ALSO = ("LICENSE",)
CODE_NEVER = ("genomes.tsv",)

# Results that are large and regenerable from the inputs. Shipping them would add ~100 MB and prove
# nothing: they are rebuilt byte-for-byte from the NCBI reference zip named in the run log.
RESULT_NEVER = ("reference_proteins.faa", "reference_symbols.tsv")
MAX_RESULT_MB = 5.0

GITIGNORE = ("# large, machine-specific, or regenerated by a run\n"
             "genomes/\nblast_dbs/\nresults/raw_tblastn/\nresults/reference_proteins.faa\n"
             "results/reference_symbols.tsv\n*.n??\n*.p??\n__pycache__/\n")

# Any home directory, written any of the ways these tools write them. Matched by shape rather than by
# this machine's username, so a WSL account whose name differs from the Windows one is caught too - the
# run log carries both (<PATH> user>/... and <PATH> user>/...).
HOMES = [
    re.compile(r"/mnt/[a-zA-Z]<PATH>/\\\s\"']+"),      # Windows drive seen from WSL
    re.compile(r"[a-zA-Z]:[\\/]Users[\\/][^\\/\s\"']+"),  # Windows
    re.compile(r"<PATH>/\\\s\"']+"),                   # macOS
    re.compile(r"<PATH>/\\\s\"']+"),                    # Linux, WSL
]


def scrub(text, placeholder="<PATH>"):
    """Remove machine-specific home directories, keeping everything that documents the run.

    Inside XML the placeholder must be escaped: a literal <PATH> dropped into cell text is read as an
    opening tag and the file will not open. That is silent - the leak check still passes - so it is
    caught here rather than by the person who downloads the workbook."""
    for rx in HOMES:
        text = rx.sub(placeholder, text)
    return text


def zipped_xml_text(path):
    """Every text member of an Office file, concatenated - what a reader of the workbook can see."""
    out = []
    with zipfile.ZipFile(path) as z:
        for n in z.namelist():
            if n.lower().endswith(XML_MEMBER):
                out.append(z.read(n).decode("utf-8", "replace"))
    return "\n".join(out)


def check_opens(path):
    """Parse every XML member of the rebuilt file. A workbook that no longer opens is a worse outcome
    than one that was never packaged, and nothing else in this script would notice."""
    import xml.etree.ElementTree as ET
    with zipfile.ZipFile(path) as z:
        for n in z.namelist():
            if n.lower().endswith((".xml", ".rels")):
                try:
                    ET.fromstring(z.read(n))
                except ET.ParseError as e:
                    sys.exit("ERROR: %s is not valid after scrubbing (%s: %s). The file was NOT "
                             "published." % (os.path.basename(path), n, e))


def put_zipped_xml(src, dst):
    """Rebuild an Office file member by member, scrubbing each text member exactly as any other text
    file is scrubbed. The sheet content, the formatting and the member order are untouched."""
    with zipfile.ZipFile(src) as zin, zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as zout:
        for it in zin.infolist():
            data = zin.read(it.filename)
            if it.filename.lower().endswith(XML_MEMBER):
                data = scrub(data.decode("utf-8", "replace"), "&lt;PATH&gt;").encode("utf-8")
            zout.writestr(it, data)
    check_opens(dst)


def put(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if src.lower().endswith(ZIPPED_XML):
        put_zipped_xml(src, dst)
        return
    if src.lower().endswith(BINARY):
        shutil.copy2(src, dst)
        return
    t = scrub(open(src, encoding="utf-8", errors="replace").read())
    if dst.endswith(".sh"):
        t = re.sub(r'^REFERENCE=.*$', 'REFERENCE="/path/to/human_GCF_000001405.40.zip"   '
                                     '# NCBI Datasets: Protein (FASTA) + Annotation features (GFF)',
                   t, flags=re.M)
        t = re.sub(r'^DB_DIR=.*$', 'DB_DIR="/path/to/blast_databases"                 '
                                   '# NOT inside OneDrive/Dropbox', t, flags=re.M)
    open(dst, "w", encoding="utf-8", newline="\n").write(t)


def verify_against_run_log(dst):
    """The run log records the MD5 of every script used. Check the code being PUBLISHED against it.

    A package whose code has moved on since the run is the worst kind of wrong: it looks complete, the
    README invites the reader to verify the checksum, and the checksum does not match. Shipping it is
    worse than shipping no checksums at all, so this is an error, not a warning."""
    import hashlib
    rdir = os.path.join(dst, "results")
    logs = [f for f in sorted(os.listdir(rdir)) if f.endswith("_run_log.txt")]
    bad, checked = [], 0
    for lg in logs:
        for ln in open(os.path.join(rdir, lg), encoding="utf-8", errors="replace"):
            m = re.match(r"\s*(\S+\.(?:py|sh|faa))\s+md5\s+([0-9a-f]{32})", ln)
            if not m:
                continue
            name, want = m.group(1), m.group(2)
            src = os.path.join(HERE, os.path.basename(name))
            if not os.path.exists(src):
                continue
            checked += 1
            got = hashlib.md5(open(src, "rb").read()).hexdigest()
            if got != want:
                bad.append("  %-22s run log %s, packaged %s" % (os.path.basename(name), want, got))
    if bad:
        print("\nCHECKSUM MISMATCH - the packaged code is NOT the code that produced results/:")
        for b in bad:
            print(b)
        print("Re-run the analysis with the current code, then package again. Nothing was published.")
        shutil.rmtree(dst, ignore_errors=True)
        sys.exit(1)
    return checked


def main():
    ap = argparse.ArgumentParser(description="Build the GitHub upload folder for this analysis")
    ap.add_argument("--out", default=os.path.join(os.path.expanduser("~"), "AGTR2_github", NAME),
                    help="destination (default: ~/AGTR2_github/%s)" % NAME)
    a = ap.parse_args()
    dst = os.path.abspath(a.out)
    if os.path.commonpath([dst, HERE]) == HERE:
        sys.exit("ERROR: --out must not be inside the analysis folder (%s)" % HERE)
    shutil.rmtree(dst, ignore_errors=True)

    skipped = []

    # ---------------------------------------------------------------- code, beside this script
    for f in sorted(os.listdir(HERE)):
        s = os.path.join(HERE, f)
        if not os.path.isfile(s) or f in CODE_NEVER:
            continue
        if f.endswith(CODE_EXT) or f in CODE_ALSO:
            put(s, os.path.join(dst, f))

    # ---------------------------------------------------------------- results of the published run
    rdir = os.path.join(HERE, "results")
    if not os.path.isdir(rdir):
        sys.exit("ERROR: no results/ directory in %s - run the analysis first" % HERE)
    for f in sorted(os.listdir(rdir)):
        s = os.path.join(rdir, f)
        if os.path.isdir(s):
            skipped.append("%-34s directory, regenerated by a run" % ("results/" + f))
        elif f in RESULT_NEVER:
            skipped.append("%-34s %.0f MB, rebuilt from the NCBI reference in the run log"
                           % ("results/" + f, os.path.getsize(s) / 1e6))
        elif os.path.getsize(s) > MAX_RESULT_MB * 1e6:
            skipped.append("%-34s %.1f MB, over the %.0f MB cap"
                           % ("results/" + f, os.path.getsize(s) / 1e6, MAX_RESULT_MB))
        else:
            put(s, os.path.join(dst, "results", f))

    # ---------------------------------------------------------------- genomes.tsv, paths rewritten
    g = os.path.join(HERE, "genomes.tsv")
    if os.path.exists(g):
        head, rows, bad = [], [], []
        for ln in open(g, encoding="utf-8"):
            if ln.startswith("#"):
                head.append(ln.rstrip("\n"))
            elif ln.strip():
                f = [x.strip() for x in ln.rstrip("\n").split("\t")]
                if len(f) < 4:
                    bad.append(f[0] if f else "?")
                    continue
                acc = f[3] if re.match(r"GC[AF]_\d+\.\d+$", f[3]) else (f[4] if len(f) > 4 else "")
                if not re.match(r"GC[AF]_\d+\.\d+$", acc):
                    bad.append(f[0])
                rows.append([f[0], f[1], f[2], acc, "genomes/%s.zip" % acc])
        if bad:
            sys.exit("ERROR: no NCBI accession found for: %s\nThe accession is what makes the run "
                     "reproducible; fix genomes.tsv before packaging." % ", ".join(bad))
        with open(os.path.join(dst, "genomes.tsv"), "w", encoding="utf-8", newline="") as fh:
            fh.write("\n".join(head) + "\n")
            fh.write("# The last column assumes each assembly was downloaded to genomes/<accession>.zip "
                     "- edit it to suit.\n")
            csv.writer(fh, delimiter="\t", lineterminator="\n").writerows(rows)
    open(os.path.join(dst, ".gitignore"), "w", encoding="utf-8", newline="\n").write(GITIGNORE)

    # ---------------------------------------------------------------- check what was actually written
    # Rather than trusting the substitutions: this machine's username must be gone, and no home
    # directory of any shape may survive.
    leaks, total = [], 0
    user = os.path.basename(os.path.expanduser("~")).lower()
    for root, _, files in os.walk(dst):
        for f in sorted(files):
            q = os.path.join(root, f)
            total += os.path.getsize(q)
            print("  %-46s %9.1f KB" % (os.path.relpath(q, dst).replace("\\", "/"),
                                        os.path.getsize(q) / 1024))
            if f.lower().endswith(ZIPPED_XML):
                body = zipped_xml_text(q)          # read INSIDE it; it is XML, not an opaque blob
            elif f.lower().endswith(BINARY):
                # Best effort only: an image or PDF is compressed, so this catches a path sitting in
                # plain metadata and nothing deeper. Figures made by matplotlib carry no file paths.
                body = open(q, "rb").read().decode("latin-1", "replace")
            else:
                body = open(q, encoding="utf-8", errors="replace").read()
            why = ["username"] if user in body.lower() else []
            why += ["home path %s" % rx.search(body).group(0) for rx in HOMES if rx.search(body)]
            if why:
                leaks.append("%s (%s)" % (os.path.relpath(q, dst), "; ".join(why)))

    print("\n%s\ntotal %.0f KB" % (dst, total / 1024))
    if skipped:
        print("deliberately not packaged:")
        for s in skipped:
            print("  " + s)
    print("local paths still present in: %s" % ("\n  " + "\n  ".join(leaks) if leaks else "none"))
    n = verify_against_run_log(dst)
    print("code matches the run log: %d checksum(s) verified" % n)
    if not os.path.exists(os.path.join(dst, "LICENSE")):
        print("WARNING: no LICENSE file - GitHub will show the repository as 'All rights reserved'")
    if not os.path.exists(os.path.join(dst, "README.md")):
        print("WARNING: no README.md - the folder will have no front page on GitHub")
    return 1 if leaks else 0


if __name__ == "__main__":
    sys.exit(main())
